// tools/imgroom_bundle_lib.mjs — rollup+terser で ImageRoom を ESM 1 個にまとめる共通関心（v2.36 §63）
// 正は分割ファイル（wwwroot/…）。ここが読む source を編集し、ビルドで派生物を再生成する。
// 依存は tools/deps/ に隔離（terser/rollup）。
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const ROOT = join(HERE, '..');
const DEPS = join(HERE, 'deps', 'node_modules');

const rollup = await import(pathToFileURL(join(DEPS, 'rollup', 'dist', 'rollup.js')).href);
const { minify } = await import(pathToFileURL(join(DEPS, 'terser', 'main.js')).href);

export async function buildBundle() {
	const input = join(ROOT, 'wwwroot', 'img_room.js');
	const { output } = await (await rollup.rollup({
		input,
		treeshake: true,
		onwarn(w, def) {
			if (w.code === 'CIRCULAR_DEPENDENCY' || w.code === 'EVAL') return; // 分割ファイル側の import 循環は ESM 実態どおり許容
			def(w);
		},
	})).generate({ format: 'es', inlineDynamicImports: true });
	const code = output[0].code;
	const min = await minify(code, { module: true, ecma: 2020, mangle: true, compress: { ecma: 2020, passes: 2 } });
	if (min.error) throw new Error('terser: ' + min.error);
	const banner = '/* ImageRoom one-file bundle. GENERATED by tools/imgroom_bundle_lib.mjs — ' +
		'canonical source is the split files under wwwroot/ (edit those, then rebuild). */\n';
	return banner + min.code;
}
