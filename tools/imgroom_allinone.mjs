// tools/imgroom_allinone.mjs — CSS と JS を内包した「まるまる 1 個」の HTML を生成（v2.36 §63）
// 正は分割ファイル（wwwroot/img_room.html / css / modules）。本スクリプトは派生物を
// wwwroot/one/img_room_allinone.html に書き出すだけ（再生成前提・編集対象は常に分割側）。
//   使い方: npm run imgallinone（または node tools/imgroom_allinone.mjs）
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { ROOT, buildBundle } from './imgroom_bundle_lib.mjs';

const htmlPath = join(ROOT, 'wwwroot', 'img_room.html');
const html = readFileSync(htmlPath, 'utf8');

// 1) JS: module script を terser minify 済みバンドルのインライン化へ差し替え
const bundle = await buildBundle();
let out = html.replace('<script type="module" src="./img_room.js"></script>', '<script type="module">\n' + bundle + '\n</script>');
if (out === html) throw new Error('img_room.html のスクリプト差し替えに失敗（構成変化？ tools/imgroom_allinone.mjs 更新）');

// 2) CSS: <link rel="stylesheet" href="./css/….css"> を <style> に展開（入れ子は相対で再帰）
const cssToInline = (href, seen = new Set()) => {
	const p = join(ROOT, 'wwwroot', href.replace(/^\.\//, ''));
	if (seen.has(p)) return '';
	seen.add(p);
	const css = readFileSync(p, 'utf8');
	return css.replace(/@import\s+url\(["']?([^"')]+)["']?\);/g, (_, sub) => cssToInline(join(dirname(href), sub), seen));
};
out = out.replace(/<link\s+rel="stylesheet"\s+href="([^"]+)"\s*\/?>/g, (_, href) => '<style>\n' + cssToInline(href) + '\n</style>');

// 3) 外部 js 参照が残っていたら展開（module import をインライン化済み。通常の src="…" もあれば同様に）
out = out.replace(/<script\s+src="([^"]+)"\s*><\/script>/g, (_, src) => '<script>\n' + readFileSync(join(ROOT, 'wwwroot', src.replace(/^\.\//, '')), 'utf8') + '\n</script>');

const oneDir = join(ROOT, 'wwwroot', 'one');
mkdirSync(oneDir, { recursive: true });
const outPath = join(oneDir, 'img_room_allinone.html');
writeFileSync(outPath, '<!-- GENERATED by tools/imgroom_allinone.mjs — canonical source is wwwroot/img_room.html + css + modules (edit those, then rebuild) -->\n' + out);
console.log(`img_room_allinone.html: ${(out.length / 1024).toFixed(1)} KB → wwwroot/one/`);
